#!/usr/bin/env python3
"""Verify release bytes and local documentation links, without running experiments."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
def main():
    manifest=ROOT/'MANIFEST.sha256'
    failures=[];tracked=set()
    for line in manifest.read_text().splitlines():
        h,name=line.split('  ',1);p=ROOT/name;tracked.add(name)
        if not p.is_file() or hashlib.sha256(p.read_bytes()).hexdigest()!=h:
            failures.append({'kind':'digest_mismatch','path':name})
    for f in sorted(ROOT.rglob('*.md')):
        for raw in re.findall(r'\[[^\]\n]*\]\(([^)]+)\)',f.read_text()):
            dest=raw.strip().split(' "',1)[0].strip('<>')
            if '://' in dest or dest.startswith(('mailto:','#')):continue
            target=dest.split('#',1)[0]
            if target and not (f.parent/target).exists():
                failures.append({'kind':'broken_document_link','source':str(f.relative_to(ROOT)),'target':target})
    # Outputs generated by a reviewer are not release assets. The list, not arbitrary
    # additional files, defines the expected reviewed release content.
    report={'status':'PASS' if not failures else 'FAIL','manifest_entries':len(tracked),
            'failures':failures,'scope':'Release bytes and local Markdown links only; not execution/scientific validation'}
    print(json.dumps(report,indent=2))
    return 0 if not failures else 1
if __name__=='__main__':raise SystemExit(main())
